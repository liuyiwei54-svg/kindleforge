import puppeteer from 'puppeteer-core';
const b = await puppeteer.launch({executablePath:'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',headless:'new',args:['--no-sandbox']});
const p = await b.newPage();
p.on('console', m => console.log('CONSOLE', m.type(), m.text().slice(0,300)));
p.on('pageerror', e => console.log('PAGEERROR', String(e).slice(0,300)));
p.on('requestfailed', r => console.log('REQFAIL', r.url().slice(0,100), r.failure()?.errorText));
await p.goto('http://127.0.0.1:3100/convert',{waitUntil:'networkidle2'});
await p.waitForSelector('input[type=file]');
const i = await p.$('input[type=file]');
await i.uploadFile('/tmp/kf-samples/zh-utf8.txt');
await new Promise(r=>setTimeout(r,1500));
console.log('--- after upload ---');
console.log((await p.evaluate(()=>document.body.innerText)).slice(0,1200));
const btn = await p.evaluate(()=>{const b=[...document.querySelectorAll('button')].find(b=>/开始转换/.test(b.textContent||'')); if(b){b.click();return b.textContent} return null});
console.log('btn:', btn);
await new Promise(r=>setTimeout(r,8000));
console.log('--- after 8s ---');
console.log((await p.evaluate(()=>document.body.innerText)).slice(0,1600));
await b.close();
